test('đặt PIN, mở lại offline, từ chối mã sai và tự khóa khi ẩn', async ({ page, context }) => {
  await page.goto('/')
  await page.getByLabel('Tên hoặc biệt danh').fill('Nhi')
  await page.getByRole('button', { name: 'Lưu và bắt đầu' }).click()
  await page.getByRole('button', { name: 'Cài đặt', exact: true }).click()
  await page.getByRole('button', { name: 'Đặt mã PIN' }).click()
  await page.getByLabel('Mã PIN mới (6 số)', { exact: true }).fill('247913')
  await page.getByLabel('Nhập lại mã PIN mới').fill('247913')
  await page.getByRole('button', { name: 'Lưu mã PIN' }).click()
  await expect(page.getByRole('button', { name: 'Khóa ngay' })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('thuong-em:screen-lock:v1'))).not.toContain('247913')
  await page.getByRole('button', { name: 'Khóa ngay' }).click()
  await expect(page.getByRole('heading', { name: 'Thương Em đã khóa' })).toBeVisible()
  await expect(page.getByRole('navigation')).toHaveCount(0)
  await page.waitForFunction(() => navigator.serviceWorker.controller)
  await context.setOffline(true)
  await page.reload()
  await page.clock.install()
  await page.getByLabel('Mã PIN', { exact: true }).fill('111111')
  await page.getByRole('button', { name: 'Mở khóa' }).click()
  await expect(page.getByRole('alert')).toContainText('Mã PIN chưa đúng')
  await page.clock.fastForward(5500)
  await page.getByLabel('Mã PIN', { exact: true }).fill('247913')
  await page.getByRole('button', { name: 'Mở khóa' }).click()
  await expect(page.getByRole('heading', { name: 'Chào Nhi' })).toBeVisible()
  await page.evaluate(() => window.dispatchEvent(new Event('pagehide')))
  await expect(page.getByRole('heading', { name: 'Thương Em đã khóa' })).toBeVisible()
})
